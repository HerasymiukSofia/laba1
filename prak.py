a = 10
b = 3

print("Початкові числа: a =", a, ", b =", b)
print("-" * 30)

# Додавання (+)
sum_result = a + b
print("Додавання (a + b):", sum_result)

# Віднімання (-)
sub_result = a - b
print("Віднімання (a - b):", sub_result)

# Множення (*)
mult_result = a * b
print("Множення (a * b):", mult_result)

# Звичайне ділення (/) — завжди повертає дробове число (float)
div_result = a / b
print("Звичайне ділення (a / b):", div_result)

# Цілочисельне ділення (//) — відкидає дробову частину
int_div_result = a // b
print("Цілочисельне ділення (a // b):", int_div_result)

# Остача від ділення (%) — скільки залишається після ділення націло
mod_result = a % b
print("Остача від ділення (a % b):", mod_result)

# Піднесення до степеня (**) — 10 у степені 3 (10 * 10 * 10)
pow_result = a ** b
print("Піднесення до степеня (a ** b):", pow_result)